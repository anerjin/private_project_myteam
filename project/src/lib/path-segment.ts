/**
 * URL 경로 조각을 «사람이 적은 값»으로 되돌린다.
 *
 * ## 왜 필요한가
 *
 * 자료 slug 에 한글이 들어갑니다(`dinov2-라벨-없이-배우는-범용-시각-특징`).
 * 그런데 경로를 읽는 두 곳이 모두 **퍼센트 인코딩된 문자열**을 줍니다:
 *
 * | 어디 | 무엇을 주는가 |
 * | --- | --- |
 * | `usePathname()` (화면) | `dinov2-%EB%9D%BC%EB%B2%A8-…` |
 * | `proxy` 가 넘긴 경로 헤더 (서버) | 같은 인코딩 형태 |
 *
 * 헤더는 애초에 인코딩되어 있어야 합니다 — HTTP 헤더 값은 ByteString 이라
 * 한글을 그대로 넣으면 `fetch` 가 던집니다(이 저장소에서 실제로 겪었습니다).
 * 그러니 **읽는 쪽에서 푸는 것이 맞습니다.**
 *
 * 안 풀면 두 가지가 한꺼번에 틀어집니다:
 *
 * 1. 빵부스러기가 조각을 그대로 그려 주소창 문자열이 제목 자리에 나옵니다
 * 2. 그 값으로 `titleBySlug` 를 찾으므로 **DB 가 못 찾고**, 그래서 1번이 계속됩니다
 *
 * ## 던지지 않습니다
 *
 * `decodeURIComponent` 는 `%` 하나만 있어도 `URIError` 를 던집니다.
 * 빵부스러기는 **모든 화면의 헤더**에 있으므로, 여기서 던지면 주소 하나 때문에
 * 화면 전체가 죽습니다. 못 풀면 원문을 그대로 돌려줍니다 — 보기에 나쁠 뿐
 * 화면은 뜹니다.
 */
export function decodeSegment(segment: string): string {
  try {
    return decodeURIComponent(segment);
  } catch {
    return segment;
  }
}
