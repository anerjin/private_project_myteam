/**
 * 아바타 목록 — **코드가 정본입니다** (`DEC-032`·`DEC-058` 과 같은 이유).
 *
 * 아바타는 사람마다 다른 «운영 데이터」가 아니라 팀이 함께 쓰는 **표현물**입니다.
 * 지금은 한 장이고, 늘어나도 「그림 파일 + 설명 한 줄」이 전부입니다.
 * DB 표를 만들면 화면·시드·백업·관리 화면이 딸려 오는데, 그 값이 아직 없습니다.
 *
 * ## 어떻게 만들었는가 — `ip-as-logo` 스킬
 *
 * https://github.com/s1dashu/ip-as-logo-skill 의 형태 규칙을 따릅니다:
 *
 * - **큰 기본 도형 4~7개**로 하나의 실루엣. 정체·표정·인식에 기여하지 않는 도형은 지운다
 * - **색은 둘** — IP 색 둘. 얼굴 표시도 그 두 색(의 명도 변주)을 다시 쓴다
 * - 뾰족한 끝·가는 선·윤곽선·글자·프레임 **없음**
 * - **32px 로 줄여도 알아볼 것** — 사라지거나 뭉개지는 요소는 키우거나 없앤다
 *
 * ### 스킬에서 «일부러» 벗어난 것 — 배경
 *
 * 스킬은 「정사각형을 배경색으로 꽉 채우고 캐릭터를 아래 모서리에서 솟게 하라」고
 * 합니다. 로고라면 맞는 규칙이지만 **아바타에서는 «색 원판에 든 그림»**이 됩니다.
 * 우리가 원하는 것은 **캐릭터 모양 그 자체**라, 배경을 비우고 잘리는 곳 없이
 * 전신을 담습니다. 나머지 규칙(도형 수·색 수·둥근 형태·32px)은 그대로입니다.
 *
 * 배경이 없다는 것은 **밝은 화면과 어두운 화면 위에 그대로 놓인다**는 뜻입니다.
 * 어느 쪽에서도 읽히는 색을 씁니다 — 새까만 부분을 크게 두면 다크 모드에서 사라집니다.
 *
 * > **스킬은 이미지 모델로 만들라고 요구합니다.** 이 세션에는 그 모델이 없어,
 * > 스킬이 정한 예외 절차(**사용자의 명시적 동의**)를 밟고 SVG 로 그렸습니다.
 * > 나중에 이미지 모델로 다시 뽑으면 `src` 만 **배경이 없는 PNG** 로 바꿉니다.
 *
 * ## 한 장 더 넣으려면
 *
 * `public/avatars/` 에 그림을 두고 아래 배열에 한 줄 추가하면 끝입니다.
 * 화면은 배열을 그대로 그립니다.
 */

export interface AvatarItem {
  /** 파일 이름과 같게 둡니다 — 어느 그림인지 목록만 보고 알 수 있게 */
  id: string;
  /** 화면에 보이는 이름 */
  name: string;
  /** 무엇을 그렸는가 — 한 줄 */
  description: string;
  /** `public/` 기준 경로. **배경이 없는 그림**입니다 */
  src: string;
  /** 쓴 색 — 다음 아바타에서 같은 조합을 반복하지 않으려고 남깁니다 */
  colors: string[];
  /** 만든 날 */
  createdAt: string;
}

