-- 저장소 최상위 파일 목록을 보관한다 (`FR-GH-002` 확장)
--
-- ## 왜 저장하는가 — 「원본이 사라져도」
--
-- `REQ-01 · 1.1` 이 문제로 적어 둔 것이 「참고하던 GitHub 저장소가 삭제·비공개
-- 전환되면 복구 불가」입니다. 지금까지 그때 남는 것은 요약·README 뿐이었고,
-- **무엇이 들어 있던 저장소인지**는 아무도 알 수 없었습니다. 최상위 목록은
-- 그 답의 절반을 아주 싸게 남깁니다 (등록 한 건에 API 1회, 수십 줄).
--
-- ## 왜 최상위만인가
--
-- `git/trees?recursive=1` 로 전체를 받을 수도 있지만 저장소 하나가 1만 줄이
-- 넘습니다(GDAL 이 그렇습니다). 그걸 저장하면 상세 화면의 RSC 페이로드가
-- 통째로 그만큼 커집니다 — **보이지도 않을 것을 매번 실어 보내게 됩니다.**
-- GitHub 이 첫 화면에 보여 주는 것도 최상위입니다.
--
-- `jsonb` 가 아니라 `json` 입니다: 이 값으로 **검색하지 않습니다**. 읽어서
-- 그대로 그릴 뿐이라 파싱 비용이 없는 쪽이 낫습니다.
ALTER TABLE "github_repos" ADD COLUMN "file_tree" JSON;
