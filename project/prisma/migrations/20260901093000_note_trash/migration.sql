-- 메모 휴지통 (`FR-NOTE-005`)
--
-- ## 왜 뒤늦게 생겼는가
--
-- 처음에는 **일부러 안 뒀습니다** — 「지우면 그 순간 사라진다」로 정했습니다.
-- 그런데 정리 스크립트의 조건 없는 `deleteMany({})` 한 줄로 운영자가 쓴
-- 메모가 지워졌고, **되돌릴 길이 하나도 없었습니다**: 휴지통도 없고,
-- 백업은 이 표가 생기기 이틀 전 것뿐이었습니다.
--
-- `check:delete` 가 그 한 줄을 이제 막지만, 그건 **내 실수 하나**를 막는
-- 것입니다. 사람이 잘못 누르는 것은 못 막습니다.
--
-- ## 자료의 휴지통과 다릅니다
--
-- 자료는 30일 뒤 `CLEANUP_TRASH` 가 비웁니다(`FR-RES-008`). 메모는
-- **자동으로 안 비웁니다** — 「30일 뒤 조용히 사라지는 것」이 바로 이 기능이
-- 생긴 이유이기 때문입니다. 비우는 것은 사람이 합니다.
ALTER TABLE "notes" ADD COLUMN "deleted_at" TIMESTAMP(3);
