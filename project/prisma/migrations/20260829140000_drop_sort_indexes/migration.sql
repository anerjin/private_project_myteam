-- 정렬 인덱스 4개를 되돌린다 (DEC-052 개정)
--
-- ## 규모를 잘못 봤습니다
--
-- `REQ-01 · 1.6` 의 3개월 성공 기준이 **자료 200건**이고, `1.7` 이 예상 규모를
-- **동시 20명 · 계정 50개 이하**로, 그리고 **「소수 인원. 유지보수 난이도가
-- 낮은 구조를 우선한다」** 로 못 박아 두었습니다.
--
-- 그런데 이 인덱스들은 **10만 건 벤치**를 근거로 넣었습니다. 목표의 500배입니다.
--
-- 게다가 **측정에서도 효과가 없었습니다** — 27ms → 28ms. `DEC-052` 에 그렇게
-- 적어 두고도 「자라는 노드를 없앴다」는 이유로 남겼는데, 그 이유는
-- **100만 건을 가정한 것**이고 이 시스템에는 그런 가정을 할 근거가 없습니다.
--
--   1만 건 목록: 8~9ms   ·   NFR-PERF-001 기준: 500ms   ·   여유 55배
--
-- 인덱스는 공짜가 아닙니다(쓰기 증폭·플래너 선택지·유지보수). 효과가 측정되지
-- 않은 것을 「나중을 위해」 남기는 것이 바로 이 저장소가 넷이나 겪은
-- 「필요할 것 같아서 만들어 둔 것」입니다.
DROP INDEX IF EXISTS "resources_live_recent_idx";
DROP INDEX IF EXISTS "resources_live_popular_idx";
DROP INDEX IF EXISTS "resources_live_bookmarked_idx";
DROP INDEX IF EXISTS "resources_live_title_idx";

